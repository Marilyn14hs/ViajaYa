
-- =====================================================
-- VIAJAYA - ESQUEMA DE BASE DE DATOS
-- PostgreSQL / Supabase
-- Tablas: destinos, reservaciones y pagos
--
-- Ejecutar solamente en una base de datos nueva.
-- No ejecutar sobre la base de datos de producción.
-- =====================================================

-- 1. TABLA DESTINOS

CREATE TABLE public.destinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    ubicacion VARCHAR(200) NOT NULL,
    precio_base NUMERIC(10,2) NOT NULL,
    capacidad_diaria INTEGER NOT NULL,
    imagen_url TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT destinos_precio_base_check
        CHECK (precio_base >= 0),

    CONSTRAINT destinos_capacidad_diaria_check
        CHECK (capacidad_diaria > 0)
);


-- 2. TABLA RESERVACIONES

CREATE TABLE public.reservaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destino_id BIGINT NOT NULL,
    codigo_confirmacion VARCHAR(20) NOT NULL,
    nombre_cliente VARCHAR(150) NOT NULL,
    correo_cliente VARCHAR(200) NOT NULL,
    fecha_excursion DATE NOT NULL,
    hora_excursion TIME NOT NULL,
    cantidad_personas INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    iva NUMERIC(12,2) NOT NULL,
    total NUMERIC(12,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    eliminada BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT reservaciones_destino_id_fkey
        FOREIGN KEY (destino_id)
        REFERENCES public.destinos(id),

    CONSTRAINT reservaciones_codigo_confirmacion_key
        UNIQUE (codigo_confirmacion),

    CONSTRAINT reservaciones_cantidad_personas_check
        CHECK (cantidad_personas > 0),

    CONSTRAINT reservaciones_precio_unitario_check
        CHECK (precio_unitario >= 0),

    CONSTRAINT reservaciones_subtotal_check
        CHECK (subtotal >= 0),

    CONSTRAINT reservaciones_iva_check
        CHECK (iva >= 0),

    CONSTRAINT reservaciones_total_check
        CHECK (total >= 0),

    CONSTRAINT reservaciones_estado_check
        CHECK (estado IN (
            'Pendiente',
            'Confirmada',
            'Cancelada'
        ))
);


-- 3. TABLA PAGOS

CREATE TABLE public.pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservacion_id BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL,
    ultimo_digito_tarjeta SMALLINT,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha_pago TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pagos_reservacion_id_fkey
        FOREIGN KEY (reservacion_id)
        REFERENCES public.reservaciones(id),

    CONSTRAINT pagos_reservacion_id_key
        UNIQUE (reservacion_id),

    CONSTRAINT pagos_monto_check
        CHECK (monto >= 0),

    CONSTRAINT pagos_ultimo_digito_tarjeta_check
        CHECK (
            ultimo_digito_tarjeta >= 0
            AND ultimo_digito_tarjeta <= 9
        ),

    CONSTRAINT pagos_estado_check
        CHECK (estado IN (
            'Pendiente',
            'Aprobado',
            'Rechazado'
        ))
);

-- =====================================================
-- FIN DEL ESQUEMA VIAJAYA
-- Las claves PRIMARY KEY y UNIQUE crean sus índices
-- automáticamente en PostgreSQL.
-- =====================================================
